create table if not exists public.user_word_state (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  w_id text not null,
  saved boolean not null default false,
  known boolean not null default false,
  updated_at timestamptz not null default now()
);

create unique index if not exists user_word_state_user_id_w_id_uidx
  on public.user_word_state (user_id, w_id);

create index if not exists user_word_state_user_id_idx
  on public.user_word_state (user_id);

alter table public.user_word_state enable row level security;

drop policy if exists "Users manage own word state" on public.user_word_state;
create policy "Users manage own word state"
  on public.user_word_state
  for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

grant select, insert, update, delete
  on table public.user_word_state
  to authenticated;
grant usage, select
  on sequence public.user_word_state_id_seq
  to authenticated;
